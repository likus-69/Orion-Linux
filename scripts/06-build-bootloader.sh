#!/usr/bin/env bash
# scripts/06-build-bootloader.sh
#
# Stage 06 — install the bootloader.
#
#   - x86_64:  GRUB 2 (BIOS + UEFI), with both biosdisk and EFI binaries
#   - aarch64: GRUB-EFI (arm64-efi) + u-boot fallback on /boot firmware
#
# After this stage the system is theoretically bootable, but we
# still run stage 07 to wrap it into a bootable ISO/IMG and stage 08
# to produce release artifacts.

set -euo pipefail
source "$(dirname "$0")/lib/common.sh"

orion_current_stage="06-bootloader"
orion_banner

# --- 1. Fetch grub source ----------------------------------------------------
orion_run_stage "fetch" "download grub ${LFS_VERSIONS[grub]} source" -- bash -c '
  cd '"$ORION_SOURCES"'
  orion_fetch https://ftp.gnu.org/gnu/grub/grub-'"${LFS_VERSIONS[grub]}"'.tar.xz
  rm -rf grub-'"${LFS_VERSIONS[grub]}"'
  tar xf grub-'"${LFS_VERSIONS[grub]}"'.tar.xz
  chown -R root:root grub-'"${LFS_VERSIONS[grub]}"'
'

# --- 2. Build grub (with platform-appropriate target) ------------------------
orion_run_stage "build-grub" "build grub for $ORION_ARCH" -- bash -c '
  orion_chroot "
    set -e
    cd /sources/grub-'"${LFS_VERSIONS[grub]}"'
    # Both core (BIOS x86_64) and EFI builds are independent; build both
    # but only install the one for our arch.
    case "'"$ORION_ARCH"'" in
      x86_64)
        # First: the PC/i386-pc build (BIOS)
        mkdir -p build-bios && cd build-bios
        ../configure --prefix=/usr           \
                     --sbindir=/usr/sbin     \
                     --sysconfdir=/etc       \
                     --disable-efiemu        \
                     --disable-werror
        make '"$MAKEFLAGS"'
        make install
        cd ..
        # Then: the x86_64-efi build (UEFI)
        mkdir -p build-efi && cd build-efi
        ../configure --prefix=/usr           \
                     --sbindir=/usr/sbin     \
                     --sysconfdir=/etc       \
                     --with-platform=efi     \
                     --disable-werror
        make '"$MAKEFLAGS"'
        make install
        cd ..
        ;;
      aarch64)
        # Single EFI build
        mkdir -p build-efi && cd build-efi
        ../configure --prefix=/usr           \
                     --sbindir=/usr/sbin     \
                     --sysconfdir=/etc       \
                     --with-platform=efi     \
                     --target=aarch64        \
                     --disable-werror
        make '"$MAKEFLAGS"'
        make install
        cd ..
        ;;
    esac
  "
'

# --- 3. Generate grub.cfg template ------------------------------------------
orion_run_stage "grub-cfg" "write /boot/grub/grub.cfg template" -- bash -c '
  set -e
  mkdir -p '"$LFS"'/boot/grub
  v='"${LFS_VERSIONS[linux]}"'
  uuid=$(uuidgen)
  cat > '"$LFS"'/boot/grub/grub.cfg <<EOF
# grub.cfg — generated by Orion Linux stage 06
# Edit to add kernel command-line options for your hardware

set default="0"
set timeout=5

insmod part_msdos
insmod part_gpt
insmod ext2
insmod squashfs
insmod loopback
insmod all_video
insmod gfxterm
insmod gettext

load_env -f /boot/grub/grubenv

set orion_kernel="$v"
set orion_root_uuid="$uuid"

menuentry "Orion Linux $v (normal)" {
    set gfxpayload=keep
    insmod linux
    linux /boot/vmlinuz-$v root=UUID=\$orion_root_uuid ro \
        rootflags=defaults \
        systemd.show_status=1 \
        loglevel=3 \
        \$extra_cmdline
    initrd /boot/initrd.img-$v 2>/dev/null
}

menuentry "Orion Linux $v (recovery, single-user)" {
    linux /boot/vmlinuz-$v root=UUID=\$orion_root_uuid ro single \
        systemd.unit=rescue.target \
        loglevel=3
}

menuentry "Orion Linux $v (verbose boot)" {
    linux /boot/vmlinuz-$v root=UUID=\$orion_root_uuid ro \
        systemd.show_status=1 \
        systemd.log_level=debug \
        loglevel=7
}
EOF
  chmod 0644 '"$LFS"'/boot/grub/grub.cfg
'

# --- 4. Install bootloader to the $LFS image ----------------------------------
# NOTE: this only writes the files into $LFS. The actual `grub-install`
# (which writes the MBR / EFI BootXXXX entry) happens inside the
# installer at install time, because we need a real block device.
orion_run_stage "install-shim" "install shim + mok for UEFI Secure Boot path" -- bash -c '
  if [[ "'"$ORION_ARCH"'" == "x86_64" ]]; then
    # Shim is signed by Microsoft for secure boot. Orion Linux does
    # NOT ship a signed shim — installer disables Secure Boot for now.
    echo "    shim: x86_64 secure boot disabled by default (signed shim not shipped)"
  else
    # aarch64 SBCs usually ship their own U-Boot; nothing to install here.
    echo "    shim: aarch64 — relying on board firmware + grub-efi"
  fi
'

# --- 5. Regenerate initramfs (if available) ---------------------------------
orion_run_stage "initramfs" "regenerate initramfs (dracut or mkinitramfs)" -- bash -c '
  if orion_chroot "command -v dracut >/dev/null 2>&1"; then
    orion_chroot "
      dracut --kver '"${LFS_VERSIONS[linux]}"' --force \
             --add dmsquash --add livenet \
             /boot/initrd.img-'"${LFS_VERSIONS[linux]}"'
    "
  else
    echo "    dracut not built yet; initramfs will be generated by installer"
  fi
'

orion_log "stage 06 complete — bootloader ready"
