#!/usr/bin/env bash
# scripts/00-host-prepare.sh
#
# Stage 00 — prepare the host build environment.
#
# - Verifies host toolchain meets LFS 12.3 minimum versions
# - Creates the build user 'orionlfs'
# - Creates LFS=/mnt/orion and /sources
# - Sets up the cross-toolchain target triplet
# - Fetches the LFS packages list + wget-meta for the next stages
#
# Safe to re-run; will skip already-done steps.

set -euo pipefail
source "$(dirname "$0")/lib/common.sh"

orion_current_stage="00-host-prepare"
orion_banner

# --- 1. Host checks ----------------------------------------------------------
orion_run_stage "host-checks" "verify host meets LFS 12.3 minimum versions" -- \
  bash -c 'orion_check_host'

# --- 2. Build user -----------------------------------------------------------
orion_run_stage "build-user" "create $ORION_LFS_USER build user" -- bash -c '
  if id -u "'"$ORION_LFS_USER"'" >/dev/null 2>&1; then
    echo "    user '"$ORION_LFS_USER"' already exists"
  else
    useradd -m -G "$(id -gn "$USER")" -s /bin/bash "'"$ORION_LFS_USER"'"
    # No password — only root can su to this user
    passwd -l "'"$ORION_LFS_USER"'" >/dev/null
    echo "    created user '"$ORION_LFS_USER"'"
  fi
'

# --- 3. Directory layout -----------------------------------------------------
orion_run_stage "dirs" "create build dirs" -- bash -c '
  mkdir -p '"$LFS"'/{sources,tools,usr,etc,var,run,tmp}
  mkdir -p '"$LFS"'/{bin,lib,lib64,sbin,boot,dev,proc,sys,home,mnt,opt,root,srv}
  ln -sfn tools/bin '"$LFS"'/bin
  ln -sfn tools/lib '"$LFS"'/lib
  [[ "'"$ORION_ARCH"'" == "x86_64" ]] && ln -sfn tools/lib '"$LFS"'/lib64
  chmod 1777 '"$LFS"'/tmp
  chown -R '"$ORION_LFS_USER"':'"$(id -gn "$ORION_LFS_USER")"'" '"$LFS"'/sources '"$LFS"'/tools
  echo "    '"$LFS"' ready"
'

# --- 4. Symlink /tools so the toolchain is reachable post-chroot -------------
orion_run_stage "tools-symlink" "symlink /tools -> '"$LFS"'/tools" -- bash -c '
  if [[ -L /tools ]]; then
    echo "    /tools symlink exists"
  else
    ln -sfn '"$LFS"'/tools /tools
  fi
'

# --- 5. Source fetch manifest ------------------------------------------------
# The wget-list mirrors the LFS book's official package list, frozen at 12.3.
orion_run_stage "fetch-list" "download the LFS 12.3 wget-list" -- bash -c '
  set -e
  manifest='"$ORION_SOURCES"'/wget-list-12.3
  if [[ -f "$manifest" ]]; then
    echo "    manifest cached at $manifest"
  else
    curl -fL -o "$manifest" \
      https://anduin.linuxfromscratch.org/BLFS/conglomeration/wget/wget-list-12.3 \
      || curl -fL -o "$manifest" \
        https://raw.githubusercontent.com/lfs-book/lfs-packages/main/wget-list-12.3
    echo "    fetched $manifest"
  fi
  # Fetch checksums file too
  if [[ ! -f '"$ORION_SOURCES"'/md5sums-12.3 ]]; then
    curl -fL -o '"$ORION_SOURCES"'/md5sums-12.3 \
      https://anduin.linuxfromscratch.org/BLFS/conglomeration/md5sums/md5sums-12.3 \
      || echo "warn: could not fetch md5sums; verifications will be skipped"
  fi
'

# --- 6. Environment file -----------------------------------------------------
orion_run_stage "env-file" "write $LFS/etc/orion-env" -- bash -c '
  cat > '"$LFS"'/etc/orion-env <<EOF
# Generated by 00-host-prepare.sh — sourced by every build stage.
export ORION_ARCH='"$ORION_ARCH"'
export ORION_VERSION='"$ORION_VERSION"'
export ORION_LFS_USER='"$ORION_LFS_USER"'
export LFS='"$LFS"'
export LFS_TGT='"$LFS_TGT"'
export LC_ALL=POSIX
export LFS LANG=POSIX LFS
export PATH=/tools/bin:/usr/bin:/bin:/usr/sbin:/sbin
export MAKEFLAGS='"$MAKEFLAGS"'
EOF
  chown '"$ORION_LFS_USER"':'"$(id -gn "$ORION_LFS_USER")"' '"$LFS"'/etc/orion-env
'

orion_log "stage 00 complete — host ready for cross-toolchain build"
