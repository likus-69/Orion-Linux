#!/usr/bin/env bash
# installer/modules/fstab.sh
#
# Finalize /etc/fstab on the installed system based on the partition layout
# from STATE and the actual UUIDs of the created partitions.

installer_module_fstab() {
  local target=/mnt/orion
  local fstab="$target/etc/fstab"

  log "generating $fstab"
  {
    echo "# Generated by orion-installer on $(date -u +%FT%TZ)"
    echo "#"
    echo "# filesystem         mountpoint       type      options                  dump pass"
    # Root
    local root_uuid; root_uuid=$(blkid -sUUID -ovalue "${STATE[part_root]}")
    printf "UUID=%-36s /                %-9s defaults,noatime        0    1\n" \
        "$root_uuid" "${STATE[root_fs]}"
    # EFI
    local efi_uuid; efi_uuid=$(blkid -sUUID -ovalue "${STATE[part_efi]}")
    printf "UUID=%-36s /boot/efi       vfat      defaults,umask=0077      0    2\n" \
        "$efi_uuid"
    # Swap
    if [[ -n "${STATE[part_swap]:-}" ]]; then
      local swap_uuid; swap_uuid=$(blkid -sUUID -ovalue "${STATE[part_swap]}")
      printf "UUID=%-36s swap             swap      defaults                0    0\n" \
          "$swap_uuid"
    fi
    # tmpfs for /tmp
    printf "%-37s /tmp             tmpfs     mode=1777,nosuid,nodev   0    0\n" "tmpfs"
  } > "$fstab"
  ok "fstab written"
}
